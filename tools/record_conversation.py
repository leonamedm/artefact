"""Run a scripted customer conversation through the real agent and save the transcript.

Scenario file (examples/scenarios/*.txt): lines starting with "#" are metadata
("# title: ...", "# now: 2026-10-31T10:00" optional), every other non-empty line is one
customer message. Agent answers are never edited by hand.

    uv run python tools/record_conversation.py examples/scenarios/01-catalog-search.txt
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from datetime import datetime
from pathlib import Path

from dotenv import load_dotenv

from emporio_agent.agent.llm import build_chat_model
from emporio_agent.app import build_application
from emporio_agent.clock import Clock, FixedClock, SystemClock
from emporio_agent.config import PROJECT_ROOT, VAR_DIR
from emporio_agent.providers import load_chain


def parse_scenario(path: Path) -> tuple[dict[str, str], list[str]]:
    meta: dict[str, str] = {}
    turns: list[str] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        if line.startswith("#"):
            key, _, value = line.lstrip("# ").partition(":")
            meta[key.strip().lower()] = value.strip()
        else:
            turns.append(line)
    if not turns:
        raise SystemExit(f"{path}: no customer messages")
    return meta, turns


def git_version() -> str:
    try:
        sha = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            capture_output=True,
            text=True,
            check=True,
            cwd=PROJECT_ROOT,
        ).stdout.strip()
        dirty = subprocess.run(
            ["git", "status", "--porcelain", "src"],
            capture_output=True,
            text=True,
            check=True,
            cwd=PROJECT_ROOT,
        ).stdout.strip()
        return f"{sha}{' (uncommitted changes)' if dirty else ''}"
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("scenario", type=Path)
    parser.add_argument("--out", type=Path, help="default: examples/<scenario name>.md")
    parser.add_argument("--provider", help="use only this LLM provider (name or number)")
    args = parser.parse_args()

    load_dotenv(PROJECT_ROOT / ".env")
    meta, turns = parse_scenario(args.scenario)
    clock: Clock = (
        FixedClock(datetime.fromisoformat(meta["now"])) if "now" in meta else (SystemClock())
    )
    chain = load_chain(args.provider)
    app = build_application(VAR_DIR, build_chat_model(chain), clock)
    assert app.conversations is not None
    app.context.session_id = app.conversations.create_session(clock.now())

    history: list[dict] = []
    served_models: set[str] = set()
    body: list[str] = []
    for text in turns:
        result = app.agent.respond(history, text)
        history.extend(result.messages)
        if result.model:
            served_models.add(result.model)
        body.append(f"**Cliente:** {text}\n")
        body.append(f"**Empório:** {result.reply}\n")
        if result.traces:
            calls = "\n".join(
                f"{t.name}({t.arguments})\n→ {json.dumps(t.result, ensure_ascii=False)}"
                for t in result.traces
            )
            body.append(
                f"<details><summary>Tools called: {', '.join(t.name for t in result.traces)}"
                f"</summary>\n\n```text\n{calls}\n```\n\n</details>\n"
            )

    title = meta.get("title", args.scenario.stem)
    header = [
        f"# {title}\n",
        f"- **Scenario:** {meta.get('scenario', '-')}",
        f"- **Recorded:** {datetime.now().astimezone():%Y-%m-%d %H:%M %Z}",
        f"- **Agent clock:** {clock.now():%Y-%m-%d %H:%M} (America/Campo_Grande)",
        f"- **Model served:** {', '.join(sorted(served_models)) or '-'}",
        "- **Provider chain:** "
        + " → ".join(f"{s.name} ({s.model} via {s.base_url})" for s in chain),
        f"- **Agent version:** {git_version()}",
        "- Transcript generated by `tools/record_conversation.py`; answers are not edited.\n",
        "---\n",
    ]
    out = args.out or PROJECT_ROOT / "examples" / f"{args.scenario.stem}.md"
    out.write_text("\n".join(header + body), encoding="utf-8")
    print(f"Saved {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
